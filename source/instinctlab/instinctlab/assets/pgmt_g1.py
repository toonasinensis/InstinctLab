from pathlib import Path

from isaaclab.assets.articulation import ArticulationCfg

from instinctlab.assets.unitree_g1 import beyondmimic_g1_29dof_actuators
from instinctlab.sim import UrdfFileCfg

ASSET_DIR = str(Path(__file__).resolve().parent / "resources")

G1_CYLINDER_CFG = ArticulationCfg(
    spawn=UrdfFileCfg(
        fix_base=False,
        replace_cylinders_with_capsules=True,
        merge_fixed_joints=True,
        asset_path=f"{ASSET_DIR}/pgmt_g1/urdf/g1/main.urdf",
        activate_contact_sensors=True,
        self_collision=True,
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, 0.76),
        joint_pos={
            ".*_hip_pitch_joint": -0.312,
            ".*_knee_joint": 0.669,
            ".*_ankle_pitch_joint": -0.363,
            ".*_elbow_joint": 0.6,
            "left_shoulder_roll_joint": 0.2,
            "left_shoulder_pitch_joint": 0.2,
            "right_shoulder_roll_joint": -0.2,
            "right_shoulder_pitch_joint": 0.2,
        },
        joint_vel={".*": 0.0},
    ),
    soft_joint_pos_limit_factor=0.9,
    actuators={
        name: actuator.replace(
            effort_limit_sim=actuator.joint_effort_limit,
            velocity_limit_sim=actuator.joint_velocity_limit,
        )
        for name, actuator in beyondmimic_g1_29dof_actuators.items()
    },
)

G1_ACTION_SCALE = {}
for a in G1_CYLINDER_CFG.actuators.values():
    e = a.effort_limit_sim
    s = a.stiffness
    names = a.joint_names_expr
    if not isinstance(e, dict):
        e = {n: e for n in names}
    if not isinstance(s, dict):
        s = {n: s for n in names}
    for n in names:
        if n in e and n in s and s[n]:
            G1_ACTION_SCALE[n] = 0.25 * e[n] / s[n]

